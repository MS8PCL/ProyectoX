const messages = { es, en };

function getLocale() {
  try {
    const locale = localStorage.getItem("px_locale");
    return Object.hasOwn(messages, locale) ? locale : "es";
  } catch {
    return "es";
  }
}

export function t(key, params = {}) {
  const keys = key.split(".");
  let val = messages[getLocale()];
  for (const k of keys) {
    if (!val || typeof val !== "object" || !Object.hasOwn(val, k)) return key;
    val = val[k];
  }
  if (typeof val !== "string") return key;
  // Return plain text for Vue's escaped bindings, never HTML or executable values.
  return val.replace(/\{(\w+)\}/g, (placeholder, name) => {
    if (!params || !Object.hasOwn(params, name)) return placeholder;
    const value = params[name];
    if (typeof value === "string" || typeof value === "boolean" ||
        (typeof value === "number" && Number.isFinite(value))) {
      return String(value);
    }
    return placeholder;
  });
}

export function setLocale(loc) {
  try {
    localStorage.setItem("px_locale", Object.hasOwn(messages, loc) ? loc : "es");
  } catch {}
  window.location.reload();
}
export function currentLocale() {
  return getLocale();
}
